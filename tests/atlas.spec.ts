import { expect, test } from '@playwright/test'

test('era explorer, tours and cited field notes work across the timeline', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/?year=1591&view=atlas')
  await expect(page).toHaveTitle('Hyderabad 1591 · Through Time')
  await expect(page.locator('canvas')).toBeVisible({ timeout: 25_000 })
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: /Read this chapter/ }).click()
  await expect(page.locator('.year-display')).toHaveText('1591CE')
  await page.getByRole('button', { name: /Explore this chapter/ }).click()
  await expect(page.locator('.field-note-panel')).toContainText('Charminar')
  await expect(page).toHaveURL(/place=charminar/)
  await page.getByRole('button', { name: 'Close tour', exact: true }).click()
  await page.getByRole('button', { name: 'Close field note', exact: true }).click()
  await page.getByRole('button', { name: /2025:/ }).click()
  await expect(page).toHaveTitle('Hyderabad 2025 · Through Time')
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: /Read this chapter/ }).click()
  await page.getByRole('button', { name: /Explore places/ }).click()
  await page.getByLabel('Find a place in 2025').fill('Cyber')
  await page.locator('.place-row').filter({ hasText: 'Cyber Towers' }).click()
  await expect(page.locator('.field-note-panel')).toContainText('Cyber Towers')
  await page.getByRole('button', { name: 'Read the source record' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('Not a photograph of the past.')
  await expect(dialog.locator('.source-list').first().getByRole('link').first()).toHaveAttribute('href', /^https:/)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  expect(errors).toEqual([])
})

