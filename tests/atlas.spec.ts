test('city life enters populated neighbourhoods and street navigation moves the camera', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/?year=2025&view=atlas')
  const canvas = page.locator('canvas')
  await expect(canvas).toHaveAttribute('data-city-districts', '25', { timeout: 30_000 })
  expect(Number(await canvas.getAttribute('data-city-buildings'))).toBeGreaterThan(1000)
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: /Read this chapter/ }).click()
  await page.getByRole('button', { name: 'City life', exact: true }).click()
  await expect(page.locator('.life-vignette')).toContainText('RECONSTRUCTED STREET SCENE')
  await expect(page.locator('.district-row')).toHaveCount(25)
  await page.locator('.district-row').filter({ hasText: 'Charminar & the old city' }).click()
  await expect(page.locator('.district-hud')).toContainText('Charminar & the old city')
  await expect.poll(async () => Number((await canvas.getAttribute('data-camera-position'))?.split(',')[1]), { timeout: 30_000 }).toBeLessThan(.3)
  await expect(canvas).toHaveAttribute('data-district', 'old-city')
  await expect(page.locator('.discovery-count')).toHaveText('1 / 25')
  await canvas.focus()
  const before = await canvas.getAttribute('data-camera-position')
  await page.keyboard.press('w')
  await expect.poll(() => canvas.getAttribute('data-camera-position')).not.toBe(before)
  await page.getByRole('button', { name: 'Reset aerial view', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Orbit', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})

